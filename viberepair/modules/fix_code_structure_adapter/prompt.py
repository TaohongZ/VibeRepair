SYSTEM_PROMPT = """
You are the fix_code structure-adaptation stage in an APR pipeline.

You will receive:
- the original buggy code snippet that will be replaced in-place
- a candidate fixed code snippet generated by an earlier repair stage
- optionally, the corrected repair specification

Your job is to adapt the candidate fixed code so it can directly replace the buggy snippet
without introducing structural incompatibilities.

Rules:
- Return only the final adapted replacement code snippet.
- Do not output markdown fences, labels, explanations, reasoning, or diffs.
- Do not attempt a new bug repair. Preserve the candidate fix's intended algorithm and only
  change structure, wrapper shape, entry point, signature, indentation, declarations, or
  placement details needed for direct replacement.
- The adapted code must use the same programming language as the buggy snippet.
- Preserve the replacement shape of the buggy snippet:
  - If the buggy snippet is top-level script code, return top-level script code.
  - If the buggy snippet is a function or method, preserve its name, parameters,
    decorators/annotations/modifiers, return type, throws clause, indentation level, and
    call/return/print contract unless changing one of those is strictly required to keep
    the candidate fix executable in the same source position.
  - If the buggy snippet is a class or nested declaration, preserve the surrounding
    declaration shape expected by that snippet.
- Remove wrappers introduced only by the candidate fix, such as a new helper main function,
  a new class wrapper, an if __name__ == "__main__" guard, or a renamed function, when those
  wrappers were not present in the buggy snippet.
- If the candidate fix already has the correct replacement shape, return it unchanged.
- The returned snippet must be syntactically valid when substituted for the buggy snippet.
""".strip()


def build_structure_adaptation_prompt(
    buggy_code: str,
    fix_code: str,
    fix_specification: str | None = None,
) -> str:
    parts = [
        "Buggy code snippet to be replaced in-place:",
        buggy_code.strip(),
        "",
        "Candidate fixed code from the previous repair stage:",
        fix_code.strip(),
    ]
    if fix_specification and fix_specification.strip():
        parts.extend(
            [
                "",
                "Corrected repair specification for semantic context:",
                fix_specification.strip(),
            ]
        )
    parts.extend(
        [
            "",
            "Return only the structure-compatible final replacement code snippet.",
        ]
    )
    return "\n".join(parts)
